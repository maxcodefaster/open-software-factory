import { readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import ts from "typescript";

const root = resolve(import.meta.dir, "../../..");
const output = resolve(import.meta.dir, "schema.generated.ts");
const temporary = resolve(import.meta.dir, `.schema-${crypto.randomUUID()}.ts`);

async function command(args: string[]) {
  const process = Bun.spawn(args, { cwd: root, stdout: "pipe", stderr: "inherit" });
  const result = await new Response(process.stdout).text();
  if ((await process.exited) !== 0) throw new Error(`Zero generation failed: ${args.join(" ")}`);
  return result;
}

async function browserProjectionTypes(path: string) {
  const source = await readFile(path, "utf8");
  const config = ts.readConfigFile(resolve(root, "tsconfig.json"), ts.sys.readFile);
  if (config.error)
    throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, "\n"));
  const options = ts.parseJsonConfigFileContent(config.config, ts.sys, root).options;
  const program = ts.createProgram([path], options);
  const syntax = program.getSourceFile(path);
  if (!syntax) throw new Error("Generated Zero projection could not be read");
  const checker = program.getTypeChecker();
  const edits: Array<{ start: number; end: number; text: string }> = [];
  function visit(node: ts.Node) {
    if (
      ts.isTypeReferenceNode(node) &&
      ts.isIdentifier(node.typeName) &&
      node.typeName.text === "ZeroCustomType"
    ) {
      const type = checker.getTypeFromTypeNode(node);
      const values = type.isUnion() ? type.types : [type];
      const literals = values.map((value) => {
        if (!value.isStringLiteral())
          throw new Error(
            "Zero projection custom types must resolve to public string values, not server imports",
          );
        return JSON.stringify(value.value);
      });
      edits.push({
        start: node.getStart(syntax),
        end: node.end,
        text: literals.sort().join(" | "),
      });
    }
    ts.forEachChild(node, visit);
  }
  visit(syntax);
  for (const statement of syntax.statements)
    if (
      ts.isImportDeclaration(statement) &&
      statement.importClause?.isTypeOnly &&
      ts.isStringLiteral(statement.moduleSpecifier) &&
      ["drizzle-zero", "./projection"].includes(statement.moduleSpecifier.text)
    )
      edits.push({ start: statement.getFullStart(), end: statement.end, text: "" });
  let output = source;
  for (const edit of edits.sort((a, b) => b.start - a.start))
    output = output.slice(0, edit.start) + edit.text + output.slice(edit.end);
  return `// @generated by bun run zero:generate. Do not edit.\n${output.trimStart()}`;
}

// Use the public generator CLI. Only its checked-in output is imported at runtime.
try {
  await command([
    "node",
    resolve(root, "node_modules/.bin/drizzle-zero"),
    "generate",
    "--config",
    "packages/zero-schema/src/projection.ts",
    "--output",
    temporary,
    "--skip-types",
    "--skip-builder",
    "--skip-declare",
  ]);
  // Resolve the declared enum types at generation time. The upstream emitter's
  // fallback retains a type import of the Drizzle-backed configuration for values
  // containing hyphens; that configuration must not become a browser dependency.
  await writeFile(temporary, await browserProjectionTypes(temporary));
  await command([resolve(root, "node_modules/.bin/biome"), "format", "--write", temporary]);
  const source = await readFile(temporary, "utf8");
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== source)
      throw new Error("Zero schema differs from Drizzle projection; run bun run zero:generate");
  } else {
    await writeFile(output, source);
  }
} finally {
  await rm(temporary, { force: true });
}
